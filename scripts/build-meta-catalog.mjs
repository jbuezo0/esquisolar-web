import fs from "node:fs/promises";
import path from "node:path";
import {fileURLToPath} from "node:url";
import {SpreadsheetFile,Workbook} from "@oai/artifact-tool";
const projectDir=process.argv[3]?path.resolve(process.argv[3]):path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const outputDir=path.resolve(process.argv[2]);
const siteUrl="https://esquisolar.com";
const products=JSON.parse(await fs.readFile(path.join(projectDir,"data","productos.json"),"utf8"));
const headers=["id","title","description","availability","condition","price","link","image_link","brand","product_type"];
const abs=p=>siteUrl+"/"+p.split("/").map(encodeURIComponent).join("/");
const rows=products.map(p=>[p.codigo,p.nombre_resumido||p.nombre,p.descripcion,"in stock","new",Number(p.precio).toFixed(2)+" GTQ",siteUrl+"/productos.html?producto="+encodeURIComponent(p.codigo),abs(p.imagen),p.marca||"Esquisolar",p.categoria]);
const cell=v=>{const s=String(v??"");return /[",\r\n]/.test(s)?'"'+s.replaceAll('"','""')+'"':s};
const csv=[headers,...rows].map(r=>r.map(cell).join(",")).join("\r\n");
await fs.writeFile(path.join(projectDir,"meta-catalog.csv"),"\ufeff"+csv+"\r\n","utf8");
const wb=Workbook.create(),sh=wb.worksheets.add("Catalogo Meta");
sh.showGridlines=false;
sh.getRangeByIndexes(0,0,rows.length+1,headers.length).values=[headers,...rows];
sh.freezePanes.freezeRows(1);
sh.getRange("A1:J1").format={fill:"#0B2748",font:{name:"Arial",bold:true,color:"#FFFFFF",size:10},horizontalAlignment:"center",verticalAlignment:"center"};
sh.getRange("A2:J"+(rows.length+1)).format.font={name:"Arial",size:10};
sh.getRange("A1:J"+(rows.length+1)).format.verticalAlignment="middle";
sh.getRange("A2:C"+(rows.length+1)).format.wrapText=true;
sh.getRange("A2:J"+(rows.length+1)).format.rowHeight=36;
sh.getRange("A:A").format.columnWidth=15;sh.getRange("B:B").format.columnWidth=34;sh.getRange("C:C").format.columnWidth=55;sh.getRange("D:F").format.columnWidth=15;sh.getRange("G:H").format.columnWidth=52;sh.getRange("I:J").format.columnWidth=22;
wb.recalculate();
await fs.mkdir(outputDir,{recursive:true});
const xlsx=await SpreadsheetFile.exportXlsx(wb);await xlsx.save(path.join(outputDir,"catalogo-meta-esquisolar.xlsx"));
const preview=await wb.render({sheetName:"Catalogo Meta",range:"A1:J8",scale:1,format:"png"});await fs.writeFile(path.join(outputDir,"catalogo-meta-esquisolar-preview.png"),new Uint8Array(await preview.arrayBuffer()));
const check=await wb.inspect({kind:"table",range:"Catalogo Meta!A1:J8",include:"values,formulas",tableMaxRows:8,tableMaxCols:10});await fs.writeFile(path.join(outputDir,"catalogo-meta-esquisolar.inspect.ndjson"),check.ndjson,"utf8");
console.log(JSON.stringify({count:rows.length,csv:path.join(projectDir,"meta-catalog.csv"),xlsx:path.join(outputDir,"catalogo-meta-esquisolar.xlsx")}));
